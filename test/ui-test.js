// Headless smoke test of the app UI with a mocked Android bridge.
const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const www = path.resolve(__dirname, '../app/src/main/assets/www');
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.addInitScript({ path: path.join(__dirname, 'mock-native.js') });
  await page.goto('file://' + www + '/index.html');
  const shot = n => page.screenshot({ path: path.join(__dirname, 'shots', n + '.png') });

  await page.waitForSelector('text=Wonder of the Seas');
  await shot('1-ships');
  await page.fill('.search', 'beyond');
  if (await page.locator('text=Wonder of the Seas').count()) throw new Error('ship search did not filter');
  await page.fill('.search', '');
  await page.click('text=Wonder of the Seas');
  await page.waitForSelector('text=7 Night Western Caribbean');
  await shot('2-sailings');
  await page.click('text=7 Night Western Caribbean');
  await page.waitForSelector('text=Deluxe Beverage Package');
  await shot('3-drinks');
  await page.click('[data-tab=wifi]'); await page.waitForSelector('text=VOOM Surf');
  await page.click('[data-tab=dining]'); await page.waitForSelector('text=Unlimited Dining Package');
  await page.click('[data-tab=excursions]'); await page.waitForSelector('text=Mayan Ruins Tour');
  await page.waitForSelector('.port-name:has-text("Cozumel")');
  await page.waitForSelector('.port-name:has-text("Roatan")');
  await page.waitForSelector('text=Roatan (2)');
  await page.click('text=Roatan (2)');
  if (await page.locator('text=Mayan Ruins Tour').count()) throw new Error('port filter did not hide Cozumel');
  await shot('4b-excursions-roatan');
  await page.click('text=All ports (4)');
  await page.waitForSelector('text=Mayan Ruins Tour');
  await shot('4-excursions');
  await page.click('button[aria-label="Price alert for Mayan Ruins Tour"]');
  await page.waitForSelector('#sheet:not([hidden])');
  await shot('5-alert-sheet');
  await page.click('text=Create alert');
  await page.waitForFunction(() => window.__bg && window.__bg.background === true);
  await page.click('[data-tab=cabins]'); await page.waitForSelector('text=Balcony');
  await shot('6-cabins');
  await page.click('text=Whole group (2-3 rooms)');
  await page.click('text=Find the best split');
  await page.waitForSelector('text=Cabin 2:');
  await page.waitForSelector('text=Interior Connecting');
  await shot('6b-group-cabins');
  await page.click('[data-root=alerts]'); await page.waitForSelector('text=Mayan Ruins Tour');
  await page.click('text=Check prices now'); await page.waitForSelector('text=Price dropped');
  await shot('7-alerts');
  await page.click('[data-root=mycruises]'); await page.waitForSelector('text=Sign in & check my purchases');
  await shot('8-mycruises');
  // My Cruises sign-in fills the Crown & Anchor number + state from the profile
  await page.fill('input[type=email]', 'me@example.com');
  await page.fill('input[type=password]', 'secret');
  await page.click('text=Sign in & check my purchases');
  await page.waitForSelector('text=Crown & Anchor · Diamond');
  await page.click('text=Use these for my cabin prices');
  await page.waitForSelector('text=Used for your cabin prices');
  await shot('9-profile');
  await page.click('[data-root=settings]'); await page.waitForSelector('text=Currency');
  const ca = await page.inputValue('input[placeholder="e.g. 123456789"]');
  if (ca !== '987654321') throw new Error('C&A not saved: ' + ca);
  await page.check('text=55 or older');
  await page.click('text=Save discounts');
  await shot('10-discounts');
  // cabins now show your price vs public
  await page.click('[data-root=explore]');
  await page.click('text=Wonder of the Seas'); await page.click('text=7 Night Western Caribbean');
  await page.click('[data-tab=cabins]'); await page.click('text=One cabin');
  await page.waitForSelector('text=Your discounts are on');
  await page.waitForSelector('text=You save');
  const all = await page.evaluate(() => window.__cabinOpts);
  await shot('11-cabins-discount');
  if (!all.some(o => o.loyaltyNumber === '987654321' && o.state === 'FL' && o.senior)) throw new Error('discounts not sent: ' + JSON.stringify(all));
  if (!all.some(o => !o.loyaltyNumber)) throw new Error('public comparison price not fetched');
  await page.click('[data-root=settings]');
  // cheapest cruise finder: Icon + Oasis, 4 adults + 2 kids, 2 connecting rooms
  await page.click('[data-root=explore]');
  await page.click('text=Find the cheapest cruise');
  await page.waitForSelector('text=Ships included');
  await page.waitForSelector('button.chip:has-text("Wonder")');
  if (await page.locator('button.chip:has-text("Beyond")').count()) throw new Error('Celebrity ship shown for Icon/Oasis');
  await page.click('text=Find the cheapest cruises');
  await page.waitForSelector('text=Checked 4 sailings');
  const first = await page.locator('.rank').first().textContent();
  await page.screenshot({ path: require('path').join(__dirname, 'shots', '12-finder.png'), fullPage: true });
  const names = await page.locator('#view .list .item .t').allTextContents();
  if (!names.every(n => /Wonder|Icon/.test(n))) throw new Error('unexpected ships ' + names);
  await page.waitForSelector('text=🚪 2 connecting Interior'); await page.waitForSelector('text=Room 2: 3 adults + 1 kid');
  await page.locator('#view .list .item').first().click();
  await page.waitForSelector('text=Find the best split');
  // back-button behaviour
  await page.click('[data-root=explore]'); await page.click('text=Wonder of the Seas');
  const handled = await page.evaluate(() => window.onNativeBack());
  if (!handled) throw new Error('back not handled');
  const atRoot = await page.evaluate(() => window.onNativeBack());
  if (atRoot) throw new Error('back at root should exit');
  if (errors.length) throw new Error('JS errors: ' + errors.join('\n'));
  console.log('UI test passed');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
